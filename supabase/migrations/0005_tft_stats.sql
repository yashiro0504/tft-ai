-- 1) 사전: Riot 문자열 ID → 작은 정수 (보드 용량 절감)
create table if not exists public.tft_dict (
  id smallint generated by default as identity primary key,
  kind text not null check (kind in ('unit', 'item', 'trait')),
  api_id text not null check (char_length(api_id) between 1 and 80),
  created_at timestamptz not null default now(),
  unique (kind, api_id)
);

-- 2) 매치
create table if not exists public.tft_matches (
  match_id text primary key check (match_id ~ '^[A-Z0-9]+_[0-9]+$'),
  platform text not null,
  set_number smallint not null,
  patch text not null,                 -- tft_patches 기준 ('16.20'). Riot game_version 에는 더 이상 패치 번호가 없다
  queue_id smallint not null,
  game_at timestamptz not null,
  game_date date not null,             -- KST 날짜 (일별 집계 키)
  game_length_sec smallint,
  tier_bucket text not null check (tier_bucket in ('CHALLENGER', 'GRANDMASTER', 'MASTER', 'DIAMOND', 'EMERALD')),
  collected_at timestamptz not null default now()
);
create index if not exists tft_matches_patch_tier_date_idx on public.tft_matches (patch, tier_bucket, game_date);
create index if not exists tft_matches_game_at_idx on public.tft_matches (game_at desc);

-- 3) 보드: 참가자 1명의 최종 상태 (판당 8행)
create table if not exists public.tft_boards (
  match_id text not null references public.tft_matches (match_id) on delete cascade,
  placement smallint not null check (placement between 1 and 8),
  level smallint not null,
  last_round smallint,                 -- Riot last_round 원값 (누적 라운드 수)
  gold_left smallint,
  damage smallint,
  unit_ids smallint[] not null,        -- 이 보드의 기물 id (중복 없음) — 탐색기 조건 검색용
  -- 고정 폭 배열 (jsonb 대비 판당 약 4배 작다: 실측 jsonb 12.6KB/판)
  units smallint[] not null,           -- 기물당 5칸 [기물, 성급, 아이템1, 아이템2, 아이템3], 빈 아이템 = 0
  traits smallint[] not null,          -- 시너지당 3칸 [시너지, 인원, 단계]
  primary key (match_id, placement),
  constraint tft_boards_units_stride check (coalesce(array_length(units, 1), 0) % 5 = 0),
  constraint tft_boards_traits_stride check (coalesce(array_length(traits, 1), 0) % 3 = 0)
);
