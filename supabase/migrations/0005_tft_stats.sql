-- 7) 매치 1건 적재 (매치 + 보드 8행을 한 트랜잭션으로, 이미 있으면 false)
create or replace function public.tft_ingest_match(p_match jsonb, p_boards jsonb)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.tft_matches
    select * from jsonb_populate_record(null::public.tft_matches, p_match || jsonb_build_object('collected_at', now()))
  on conflict (match_id) do nothing;
  if not found then
    return false;
  end if;

  insert into public.tft_boards
    select * from jsonb_populate_recordset(null::public.tft_boards, p_boards)
  on conflict (match_id, placement) do nothing;

  delete from public.tft_fetch_failures where match_id = p_match ->> 'match_id';
  return true;
end;
$$;

-- 8) 같은 판을 더 높은 티어 시드에서 다시 만났을 때 티어 구간을 올린다
create or replace function public.tft_raise_tier(p_match_ids text[], p_tier text)
returns integer
language sql
security definer
set search_path = public
as $$
  with ranked(tier, r) as (
    values ('EMERALD', 1), ('DIAMOND', 2), ('MASTER', 3), ('GRANDMASTER', 4), ('CHALLENGER', 5)
  ),
  updated as (
    update public.tft_matches m
       set tier_bucket = p_tier
      from ranked cur, ranked nxt
     where m.match_id = any (p_match_ids)
       and cur.tier = m.tier_bucket
       and nxt.tier = p_tier
       and nxt.r > cur.r
    returning 1
  )
  select count(*)::integer from updated;
$$;

-- 9) 원본 보관: 최근 p_keep_patches 개 패치만 남긴다 (보드는 cascade 로 함께 삭제)
create or replace function public.tft_prune_raw(p_keep_patches integer default 1)
returns integer
language sql
security definer
set search_path = public
as $$
  with keep as (
    select patch from public.tft_matches
     group by patch
     order by max(game_at) desc
     limit greatest(p_keep_patches, 1)
  ),
  removed as (
    delete from public.tft_matches where patch not in (select patch from keep) returning 1
  ),
  old_failures as (
    delete from public.tft_fetch_failures where updated_at < now() - interval '7 days' returning 1
  )
  select (select count(*) from removed)::integer;
$$;

-- 10) 원본 용량(MB) — 무료 플랜 한도 가드용
create or replace function public.tft_raw_size_mb()
returns numeric
language sql
security definer
set search_path = public
as $$
  select round(
    (pg_total_relation_size('public.tft_matches') + pg_total_relation_size('public.tft_boards')
     + pg_total_relation_size('public.tft_dict') + pg_total_relation_size('public.tft_seed_players'))
    / 1024.0 / 1024.0, 1);
$$;

