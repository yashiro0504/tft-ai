-- 3-1) 패치 달력: Data Dragon 최신 버전을 처음 본 시각
--      판의 패치 = game_at 이전에 처음 보인 패치 중 가장 최근 것 (수집기가 매 실행 갱신, 오차는 실행 간격 이내)
create table if not exists public.tft_patches (
  patch text primary key,              -- '16.20'
  ddragon_version text not null,       -- '16.20.1'
  first_seen_at timestamptz not null default now()
);

-- 4) 시드 선수 (수집 대상)
create table if not exists public.tft_seed_players (
  puuid_hash text primary key,         -- HMAC-SHA256 (TFT_SEED_KEY 파생 키), 중복 제거·조회용
  puuid_enc text not null,             -- AES-256-GCM 암호문 (Riot 호출 시에만 복호화)
  platform text not null,
  tier text not null,
  lp integer not null default 0,
  refreshed_at timestamptz not null default now(),  -- 리그 목록에서 마지막으로 확인된 시각
  checked_at timestamptz,              -- 마지막으로 매치 ID 를 조회한 시각
  last_match_at timestamptz            -- 받아 둔 가장 최근 판 시각 (다음 조회의 startTime)
);
create index if not exists tft_seed_players_checked_idx on public.tft_seed_players (checked_at asc nulls first);

-- 5) 실패한 매치 (다음 실행에서 재시도)
create table if not exists public.tft_fetch_failures (
  match_id text primary key,
  tier_bucket text not null,
  attempts smallint not null default 1,
  last_error text,
  updated_at timestamptz not null default now()
);

-- 6) 수집 실행 기록 (운영 확인용)
create table if not exists public.tft_collect_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  matches_added integer not null default 0,
  matches_skipped integer not null default 0,
  failures integer not null default 0,
  riot_calls integer not null default 0,
  note text
);

